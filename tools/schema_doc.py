#!/usr/bin/env python3
"""Generate schema.sql and SCHEMA.md from the production database and the code.

    cd ~/ads-l-map && python3 tools/schema_doc.py --out ~/schemadoc

Run on the host, from the service's checkout, as the service user. It reads
the database settings the way nightly.py does (DB_USER and DB_PASSWORD from
the `.env` beside app.py, or ~/.my.cnf without them) and sends the server
nothing but SHOW TABLES, SHOW CREATE TABLE, SHOW GRANTS FOR CURRENT_USER and
SELECTs on information_schema: it reads no row of any table, and no credential
is printed, logged or written. It writes two files into --out, never into the
checkout itself (deploy.sh owns that), and they are then copied into the
repository by hand and committed together:

  schema.sql  every table of `ads_l`, as SHOW CREATE TABLE gives it, sorted,
              with IF NOT EXISTS added and the AUTO_INCREMENT counter removed;
  SCHEMA.md   one section per table: columns and keys, what a row is, the
              section of METHOD.md or PATTERNS.md that defines it, the code
              that writes and reads it, the endpoints that publish it, the
              files of schema/ that created or changed it, and the service
              user's grants on it.

Written on 9 October 2026, when the tables had come to number 46 and the
hand-maintained schema.sql still described the ten of 3 October: since then
every change had gone into a dated file in schema/, so the only complete
description of the database was the database. Everything in SCHEMA.md except
the two hand-written lines per table (DESCRIPTIONS below) is derived: columns
and grants from the server, readers and writers from the SQL in the string
literals of the code, endpoints by following calls from the routes of app.py,
history from schema/*.sql and from git. So a table added without a
description, or a description left for a dropped table, is reported on
stderr rather than papered over, and so is a column the migrations do not
account for.
"""

