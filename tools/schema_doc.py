def load_settings(repo):
    """DB_USER and DB_PASSWORD from the checkout's .env, as nightly.py loads them."""
    try:
        from dotenv import load_dotenv
    except ImportError:
        return
    load_dotenv(os.path.join(repo, ".env"))


def connect():
    """As nightly.connect_db: .env if DB_USER is set, ~/.my.cnf otherwise."""
    import pymysql
    if os.getenv("DB_USER"):
        return pymysql.connect(host="localhost", user=os.getenv("DB_USER"), password=os.getenv("DB_PASSWORD"),
                               database=DATABASE, autocommit=True)
    return pymysql.connect(read_default_file=os.path.expanduser("~/.my.cnf"), database=DATABASE, autocommit=True)


def read_database(conn):
    db = {"tables": [], "create": {}, "columns": defaultdict(list), "indexes": defaultdict(dict)}
    with conn.cursor() as cur:
        cur.execute("SHOW VARIABLES LIKE 'version'")
        row = cur.fetchone()
        db["version"] = row[1] if row else "unknown"
        cur.execute("SHOW FULL TABLES")
        for name, kind in cur.fetchall():
            if kind == "BASE TABLE":
                db["tables"].append(name)
            else:
                db.setdefault("views", []).append(name)
        db["tables"].sort()
        for t in db["tables"]:
            cur.execute(f"SHOW CREATE TABLE `{t}`")
            db["create"][t] = cur.fetchone()[1]
        cur.execute(
            "SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT "
            "FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = %s ORDER BY TABLE_NAME, ORDINAL_POSITION",
            (DATABASE,))
        for t, c, typ, nullable, default in cur.fetchall():
            db["columns"][t].append({"name": c, "type": typ, "null": nullable == "YES", "default": default})
        cur.execute(
            "SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, COLUMN_NAME FROM information_schema.STATISTICS "
            "WHERE TABLE_SCHEMA = %s ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX", (DATABASE,))
        for t, index, non_unique, c in cur.fetchall():
            db["indexes"][t].setdefault(index, {"unique": not non_unique, "columns": []})["columns"].append(c)
        try:
            cur.execute("SHOW GRANTS FOR CURRENT_USER")
            db["grants"] = parse_grants(r[0] for r in cur.fetchall())
        except Exception as e:          # noqa: BLE001 -- grants are optional in the output
            db["grants"] = None
            warn(f"SHOW GRANTS FOR CURRENT_USER failed ({type(e).__name__}); SCHEMA.md will have no grants")
    return db


GRANT_RE = re.compile(r"^GRANT (?P<privs>.+?) ON (?P<obj>\S+) TO (?P<user>`[^`]*`@`[^`]*`|'[^']*'@'[^']*'|\S+)")


def parse_grants(lines):
    """Privileges per object, and the grantee. The rest of each line (which
    can carry IDENTIFIED BY PASSWORD and its hash) is dropped unread."""
    out = {"user": None, "objects": defaultdict(list)}
    for line in lines:
        m = GRANT_RE.match(line)
        if not m:
            continue
        out["user"] = m.group("user").replace("`", "'")
        obj = m.group("obj").replace("`", "")
        privs = [p.strip() for p in re.split(r",\s*(?![^()]*\))", m.group("privs"))]
        out["objects"][obj].extend(privs)
    return out


def grants_for(grants, table):
    if not grants:
        return None
    parts, wider = [], set()
    for obj, label in (("*.*", "server-wide"), (f"{DATABASE}.*", "database-wide"), (f"{DATABASE}.{table}", None)):
        privs = [p for p in grants["objects"].get(obj, []) if p != "USAGE" and p not in wider]
        wider.update(privs)
        if privs:
            parts.append(", ".join(privs) + (f" ({label})" if label else " (this table)"))
    return "; ".join(parts) if parts else "none"


