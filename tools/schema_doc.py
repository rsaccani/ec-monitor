COL_DEF = re.compile(r"^\s*`(\w+)`\s+(.+?),?\s*$")


def column_type(defn):
    """`int(10) unsigned NOT NULL DEFAULT 0` -> `int(10) unsigned`."""
    m = re.match(r"((?:enum|set)\([^)]*\)|\w+(?:\([^)]*\))?(?:\s+unsigned)?(?:\s+zerofill)?)", defn.strip(), re.I)
    return m.group(1).lower() if m else defn.strip().lower()


def parse_creates(sql):
    """{table: {column: type}} from the CREATE TABLE statements of sql."""
    out = {}
    for m in re.finditer(r"CREATE TABLE(?: IF NOT EXISTS)? `(\w+)` \((.*?)\n\)", sql, re.S):
        cols = {}
        for line in m.group(2).splitlines():
            c = COL_DEF.match(line)
            if c:
                cols[c.group(1)] = column_type(c.group(2))
        out[m.group(1)] = cols
    return out


def strip_comments(sql):
    return "\n".join(l for l in sql.splitlines() if not l.lstrip().startswith("--"))


def parse_migration(sql):
    """[(table, action, detail)] with action create/alter/grant, and the
    column changes [(table, 'add'|'modify'|'drop', column, type)]."""
    body = strip_comments(sql)
    events, changes = [], []
    for t, cols in parse_creates(body).items():
        events.append((t, "create", f"{len(cols)} columns"))
        changes.append((t, "create", None, dict(cols)))
    for m in re.finditer(r"ALTER TABLE `(\w+)`(.*?);", body, re.S):
        t, clause = m.group(1), m.group(2)
        what = []
        for a in re.finditer(r"ADD COLUMN `(\w+)` ([^,;]+?)(?:\s+AFTER `\w+`)?\s*(?:,|$)", clause):
            changes.append((t, "add", a.group(1), column_type(a.group(2))))
            what.append(f"adds {a.group(1)}")
        for a in re.finditer(r"MODIFY(?: COLUMN)? `(\w+)` ([^,;]+?)\s*(?:,|$)", clause):
            changes.append((t, "modify", a.group(1), column_type(a.group(2))))
            what.append(f"changes {a.group(1)} to {column_type(a.group(2))}")
        for a in re.finditer(r"DROP COLUMN `(\w+)`", clause):
            changes.append((t, "drop", a.group(1), None))
            what.append(f"drops {a.group(1)}")
        if re.search(r"ADD PRIMARY KEY", clause):
            what.append("new primary key")
        events.append((t, "alter", ", ".join(what) or "alters"))
    for m in re.finditer(r"GRANT (.+?) ON `?\w+`?\.`?(\w+)`? TO", body):
        events.append((m.group(2), "grant", m.group(1)))
    return events, changes


def git(repo, *args):
    try:
        r = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, text=True, timeout=60)
        return r.stdout if r.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def migrations_in_order(repo):
    """schema/*.sql in the order they were committed, which is the order
    they were applied: the file names sort otherwise within a day
    (2026-10-07-crewed-encounters.sql widens a column of a table that
    2026-10-07-nightly.sql, committed earlier, creates). Files not yet
    committed come last, by name."""
    def key(path):
        rel = os.path.relpath(path, repo)
        added = git(repo, "log", "--diff-filter=A", "--format=%ct", "--", rel).split()
        return (int(added[-1]) if added else float("inf"), rel)
    return sorted(glob.glob(os.path.join(repo, "schema", "*.sql")), key=key)


def handwritten_baseline(repo):
    """The last hand-maintained schema.sql in git: (sha, date, sql), or None.
    Tables older than schema/ (3 October 2026) were described only there."""
    for line in git(repo, "log", "--format=%h %ad", "--date=short", "--", "schema.sql").splitlines():
        sha, date = line.split()
        sql = git(repo, "show", f"{sha}:schema.sql")
        if sql and GENERATED_MARK not in sql:
            return sha, date, sql
    return None


def baseline_origin(repo, table):
    """The commit that added table's CREATE to the hand-written schema.sql."""
    out = git(repo, "log", "--reverse", "--format=%h %ad", "--date=short", "-S",
              f"CREATE TABLE IF NOT EXISTS `{table}`", "--", "schema.sql").split("\n")
    return out[0].strip() if out and out[0].strip() else None


