# Code: which function names which table, and for what

TABLE_WORD = r"(?<![\w.])`?{t}`?(?![\w])"
WRITE_KW = r"(?:INSERT(?:\s+IGNORE)?\s+INTO|REPLACE\s+INTO|DELETE\s+FROM|UPDATE)\s+"
READ_KW = r"(?<!DELETE )(?<!DELETE\n)(?:FROM|JOIN)\s+"   # the FROM of a DELETE is not a read
GENERIC_WRITE = re.compile(WRITE_KW + r"\{")
GENERIC_READ = re.compile(READ_KW + r"\{")
# SQL keywords are matched in upper case only, as the code writes them, so
# that prose such as "read from daily_x" in a log message is not SQL.
SQL_TABLE = re.compile(r"(?:INSERT(?:\s+IGNORE)?\s+INTO|REPLACE\s+INTO|DELETE\s+FROM|UPDATE|FROM|JOIN)\s+`?([a-z_][a-z0-9_]*)`?")
TABLEISH = re.compile(r"^(?:daily|monthly|nightly)_[a-z0-9_]+$")


def docstrings(node):
    """The docstring nodes under node: prose, which names tables in English."""
    out = set()
    for n in ast.walk(node):
        if isinstance(n, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and n.body:
            first = n.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant):
                out.add(id(first.value))
    return out


def string_values(node):
    """String literals under node, docstrings left out, f-strings rebuilt
    with {} for each field."""
    out = []
    skip = docstrings(node)
    for n in ast.walk(node):
        if id(n) in skip:
            continue
        if isinstance(n, ast.JoinedStr):
            out.append("".join(v.value if isinstance(v, ast.Constant) and isinstance(v.value, str) else "{}"
                               for v in n.values))
        elif isinstance(n, ast.Constant) and isinstance(n.value, str):
            out.append(n.value)
    return out


def names_used(node):
    out = set()
    for n in ast.walk(node):
        if isinstance(n, ast.Name):
            out.add(n.id)
        elif isinstance(n, ast.Attribute):
            out.add(n.attr)
    return out


def calls_made(node):
    out = set()
    for n in ast.walk(node):
        if isinstance(n, ast.Call):
            f = n.func
            if isinstance(f, ast.Name):
                out.add(f.id)
            elif isinstance(f, ast.Attribute):
                out.add(f.attr)
        # a bound method passed as a value (Thread(target=tracker.writer_loop), ("hours", self.hours_stats))
        if isinstance(n, ast.Attribute) and isinstance(n.ctx, ast.Load) and isinstance(n.value, ast.Name) \
                and n.value.id in ("self", "tracker", "sources"):
            out.add(n.attr)
    return out


def code_files(repo):
    files = [f for f in ("app.py", "sources.py", "nightly.py", "recorder.py") if os.path.exists(os.path.join(repo, f))]
    files += sorted(os.path.relpath(p, repo) for p in glob.glob(os.path.join(repo, "tools", "**", "*.py"), recursive=True)
                    if os.path.basename(p) != "schema_doc.py")
    files += sorted(os.path.relpath(p, repo) for p in glob.glob(os.path.join(repo, "tools", "**", "*.sh"), recursive=True))
    return files


def analyse_code(repo, tables):
    """Per table: {(file, function): set of 'read'/'write'/'ref'}; plus the
    functions of the service, their calls, and the routes of app.py."""
    refs = defaultdict(lambda: defaultdict(set))
    functions = {}            # (file, qualname) -> {"calls": set, "tables": {t: kinds}}
    routes = []               # (path, handler qualname)
    in_code = set()           # table-like names that the code uses in SQL
    patterns = {t: re.compile(TABLE_WORD.format(t=re.escape(t))) for t in tables}

    def kinds_in(strings, t):
        k = set()
        pat = patterns[t]
        for s in strings:
            if not pat.search(s):
                continue
            if re.search(WRITE_KW + r"`?" + re.escape(t) + r"`?(?![\w])", s):
                k.add("write")
            if re.search(READ_KW + r"`?" + re.escape(t) + r"`?(?![\w])", s):
                k.add("read")
            if s.strip("` ") == t:
                k.add("name")
        return k

    for rel in code_files(repo):
        path = os.path.join(repo, rel)
        text = open(path, encoding="utf-8").read()
        if rel.endswith(".sh"):
            for t in tables:
                if patterns[t].search(text):
                    refs[t][(rel, "")].add("write" if re.search(WRITE_KW + re.escape(t), text) else "ref")
            continue
        tree = ast.parse(text, rel)
        module_consts = {}     # NAME -> {table: kinds}
        consts_api = {}
        # Module functions that build a write statement around a table name
        # (sources._upsert): a constant made by calling one writes that table.
        builders = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)
                    and any(GENERIC_WRITE.search(s) for s in string_values(n))}
        for node in tree.body:
            if isinstance(node, ast.Assign):
                strings = string_values(node.value)
                found = {t: kinds_in(strings, t) for t in tables if any(patterns[t].search(s) for s in strings)}
                if isinstance(node.value, ast.Call) and getattr(node.value.func, "id", None) in builders:
                    found = {t: (k - {"name"}) | {"write"} for t, k in found.items()}
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        if found:
                            module_consts[target.id] = found
                        if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                            consts_api[target.id] = node.value.value
                for s in strings:
                    in_code.update(m.group(1) for m in SQL_TABLE.finditer(s) if TABLEISH.match(m.group(1)))
                    if TABLEISH.match(s):
                        in_code.add(s)

        def visit(node, qual):
            strings = string_values(node)
            used = names_used(node)
            generic_w = any(GENERIC_WRITE.search(s) for s in strings)
            generic_r = any(GENERIC_READ.search(s) for s in strings)
            found = {}
            for t in tables:
                k = kinds_in(strings, t)
                via_const = [module_consts[n][t] for n in used if n in module_consts and t in module_consts[n]]
                for ck in via_const:
                    k |= (ck - {"name"}) or {"name"}
                if not k:
                    continue
                if "name" in k:           # named as a value, used in SQL built around it
                    k.discard("name")
                    if generic_w:
                        k.add("write")
                    if generic_r:
                        k.add("read")
                    if not k:
                        k.add("ref")
                found[t] = k
                refs[t][(rel, qual)] |= k
            for s in strings:
                in_code.update(m.group(1) for m in SQL_TABLE.finditer(s) if TABLEISH.match(m.group(1)))
            functions[(rel, qual)] = {"calls": calls_made(node), "tables": found}

        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                visit(node, node.name)
                if rel == "app.py":
                    for d in node.decorator_list:
                        if isinstance(d, ast.Call) and getattr(d.func, "attr", None) == "route" and d.args:
                            routes.append((route_path(d.args[0], consts_api), node.name))
            elif isinstance(node, ast.ClassDef):
                for sub in node.body:
                    if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        visit(sub, f"{node.name}.{sub.name}")
            elif isinstance(node, ast.If):     # if __name__ == "__main__": block
                strings = string_values(node)
                if any(patterns[t].search(s) for s in strings for t in tables):
                    visit(node, "__main__")
    return refs, functions, routes, in_code


def route_path(arg, consts):
    if isinstance(arg, ast.Constant):
        return arg.value
    if isinstance(arg, ast.BinOp) and isinstance(arg.op, ast.Add):
        return route_path(arg.left, consts) + route_path(arg.right, consts)
    if isinstance(arg, ast.Name):
        return consts.get(arg.id, "{" + arg.id + "}")
    return "?"


def endpoints_by_table(functions, routes):
    """Follow calls from each route of app.py through app.py and sources.py,
    by function name, and collect the tables read on the way."""
    by_name = defaultdict(list)
    for (rel, qual) in functions:
        if rel in ("app.py", "sources.py"):
            by_name[qual.split(".")[-1]].append((rel, qual))
    out = defaultdict(set)
    for path, handler in routes:
        seen, todo = set(), [("app.py", handler)]
        while todo:
            key = todo.pop()
            if key in seen or key not in functions:
                continue
            seen.add(key)
            f = functions[key]
            for t, kinds in f["tables"].items():
                if kinds & {"read", "ref"}:
                    out[t].add(path)
            for c in f["calls"]:
                todo.extend(by_name.get(c, ()))
    return out


def family_of_nightly(repo):
    """nightly.FAMILIES, read from the source without importing it."""
    path = os.path.join(repo, "nightly.py")
    if not os.path.exists(path):
        return {}
    for node in ast.parse(open(path, encoding="utf-8").read()).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "FAMILIES" for t in node.targets):
            fam = ast.literal_eval(node.value)
            return {t: name for name, ts in fam.items() for t in ts}
    return {}


