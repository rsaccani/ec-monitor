def render_schema_sql(db, today, commit):
    out = [
        f"-- Schema of the Electronic Conspicuity Monitor, {GENERATED_MARK} on {today}",
        f"-- from the production database `{DATABASE}` (MariaDB {db['version']}), code at {commit}.",
        "-- Do not edit: change the database through a dated file in schema/, then run",
        "--   cd ~/ads-l-map && python3 tools/schema_doc.py --out ~/schemadoc",
        "-- and commit this file and SCHEMA.md as it writes them. SCHEMA.md says what each",
        "-- table holds and which code reads and writes it.",
        "--",
        "-- Each table as SHOW CREATE TABLE gives it, with IF NOT EXISTS added and the",
        "-- AUTO_INCREMENT counter removed. Load it on an empty server with",
        "--   mysql < schema.sql",
        "-- then create the service user and its grants as README.md describes.",
        "",
        f"CREATE DATABASE IF NOT EXISTS {DATABASE} CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;",
        f"USE {DATABASE};",
        "",
    ]
    for t in db["tables"]:
        ddl = re.sub(r"\s+AUTO_INCREMENT=\d+", "", db["create"][t])
        ddl = ddl.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
        out.append(ddl + ";")
        out.append("")
    return "\n".join(out)


def md_escape(s):
    return str(s).replace("|", "\\|")


def fmt_functions(keys):
    """[(file, function)] -> "`file` `f`, `g`; `other` `h`", one group per file."""
    by_file = defaultdict(list)
    for rel, qual in keys:
        by_file[rel].append(qual)
    return "; ".join(f"`{rel}`" + (" " + ", ".join(f"`{q}`" for q in quals if q) if any(quals) else "")
                     for rel, quals in by_file.items())


def program_of(rel):
    if rel in ("app.py", "sources.py"):
        return "service"
    if rel == "nightly.py":
        return "nightly"
    if rel == "recorder.py":
        return "recorder"
    return "one-off tool"


def render_schema_md(db, ctx, today, commit):
    refs, routes_by_table, families = ctx["refs"], ctx["endpoints"], ctx["families"]
    history, baseline, origins = ctx["history"], ctx["baseline"], ctx["origins"]
    grants = db.get("grants")
    group_of = {t: DESCRIPTIONS.get(t, {}).get("group", "undescribed") for t in db["tables"]}
    out = [
        "# Database schema",
        "",
        f"Generated by `tools/schema_doc.py` on {today} from the production database `{DATABASE}` "
        f"(MariaDB {db['version']}) and the code at `{commit}`. Do not edit it by hand: run the script again "
        "after each migration, as README.md describes, and commit it with `schema.sql`.",
        "",
        "Everything here is read from the database or the code except the line that says what a row is and the "
        "section of the method that defines it, which are kept in `DESCRIPTIONS` in the script. Columns and keys "
        "come from `information_schema`. Writers and readers are the functions whose SQL names the table, "
        "directly or through a constant or a list of table names (`nightly.FAMILIES`, the archive steps of "
        "`sources.py`). Endpoints are found by following calls from each route of `app.py` through `app.py` and "
        "`sources.py`. History lists the files of `schema/` that create, alter or grant on the table; tables "
        "older than that directory were described only in the hand-written `schema.sql`, whose commit is given. "
        "In the column tables, *PK* is the column's position in the primary key.",
        "",
        "Every `day` column is the UTC day of the recording the row was computed from; every `month` is "
        "`YYYY-MM`. `lat_idx` and `lon_idx` are `floor(lat * n)` and `floor(lon * n)`, with n = 4 for "
        "0.25-degree cells and 1 for 1-degree cells, and -32768 for rows with no place.",
        "",
    ]
    if grants:
        out += ["## The service user's grants", ""]
        out.append(f"As `SHOW GRANTS FOR CURRENT_USER` returned them for {grants['user']}, the user the service, "
                   "nightly.py and this script run as:")
        out.append("")
        for obj in sorted(grants["objects"]):
            privs = [p for p in grants["objects"][obj] if p != "USAGE"]
            if privs:
                out.append(f"- `{obj}`: {', '.join(privs)}")
        out.append("")
    out += ["## Contents", ""]
    for key, title, _ in GROUPS + (("undescribed", "Not described yet", ""),):
        ts = [t for t in db["tables"] if group_of[t] == key]
        if ts:
            out.append(f"- {title} ({len(ts)}): " + ", ".join(f"[`{t}`](#{t})" for t in ts))
    out.append("")
    for key, title, intro in GROUPS + (("undescribed", "Not described yet",
                                        "Tables with no entry in DESCRIPTIONS in tools/schema_doc.py."),):
        ts = [t for t in db["tables"] if group_of[t] == key]
        if not ts:
            continue
        out += [f"## {title}", "", intro, ""]
        for t in ts:
            out += render_table(t, db, refs.get(t, {}), routes_by_table.get(t, set()), families.get(t),
                                history.get(t, []), baseline, origins.get(t), grants)
    return "\n".join(out).rstrip() + "\n"


def render_table(t, db, trefs, endpoints, family, hist, baseline, origin, grants):
    d = DESCRIPTIONS.get(t, {})
    out = [f"### `{t}`", ""]
    out.append(d.get("row", "*No description.*"))
    out.append("")
    pk = []
    for name, ix in db["indexes"].get(t, {}).items():
        if name == "PRIMARY":
            pk = ix["columns"]
    out += ["| Column | Type | Default | PK |", "|---|---|---|---|"]
    for c in db["columns"].get(t, []):
        typ = c["type"] + (" NULL" if c["null"] else "")
        default = "" if c["default"] is None else c["default"]
        pos = str(pk.index(c["name"]) + 1) if c["name"] in pk else ""
        out.append(f"| `{c['name']}` | {md_escape(typ)} | {md_escape(default)} | {pos} |")
    out.append("")
    facts = []
    others = [(n, ix) for n, ix in db["indexes"].get(t, {}).items() if n != "PRIMARY"]
    if others:
        facts.append("Other indexes: " + "; ".join(
            f"`{n}` ({', '.join(ix['columns'])}){' unique' if ix['unique'] else ''}" for n, ix in others))
    facts.append("Defined in: " + (d.get("doc") or "*not given*"))
    writers = sorted(k for k, v in trefs.items() if "write" in v)
    readers = sorted(k for k, v in trefs.items() if "read" in v and "write" not in v)
    readwrite = sorted(k for k, v in trefs.items() if "read" in v and "write" in v)
    mentions = sorted(k for k, v in trefs.items() if v == {"ref"})
    core_writers = [k for k in writers if program_of(k[0]) != "one-off tool"]
    if core_writers:
        by_prog = defaultdict(list)
        for k in core_writers:
            by_prog[program_of(k[0])].append(k)
        facts.append("Written by: " + "; ".join(f"the {p}, {fmt_functions(ks)}" for p, ks in by_prog.items())
                     + (f" (nightly family `{family}`)" if family else ""))
    else:
        facts.append("Written by: *no code in this repository*")
    rs = [k for k in readers + readwrite if program_of(k[0]) != "one-off tool"]
    if rs:
        facts.append("Read by: " + fmt_functions(sorted(rs)))
    if endpoints:
        facts.append("Published through: " + ", ".join(f"`{e}`" for e in sorted(endpoints)))
    tool_w = sorted(k for k in writers if program_of(k[0]) == "one-off tool")
    tool_r = sorted(k for k in readers + mentions if program_of(k[0]) == "one-off tool")
    if tool_w:
        facts.append("Changed after the fact by one-off tools: " + fmt_functions(tool_w))
    if tool_r:
        facts.append("Read or named by one-off tools: " + fmt_functions(tool_r))
    hist_parts = []
    if origin:
        sha, _, date = origin.partition(" ")
        hist_parts.append(f"added to the hand-written `schema.sql` in `{sha}`" + (f" ({date})" if date else ""))
    for f, action, detail in hist:
        if action == "grant":
            continue
        hist_parts.append(f"`{f}` ({'created' if action == 'create' else detail})")
    granted = sorted({f for f, a, _ in hist if a == "grant"})
    facts.append("History: " + ("; ".join(hist_parts) if hist_parts else "*not in any migration*")
                 + (f". Grants in {', '.join(f'`{g}`' for g in granted)}" if granted else ""))
    g = grants_for(grants, t)
    if g is not None:
        facts.append(f"Service user's privileges: {g}")
    out += [f"- {f}" for f in facts]
    out.append("")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True, help="directory for schema.sql and SCHEMA.md (created if missing)")
    ap.add_argument("--repo", default=None,
                    help="the service's checkout (default: the directory above this script if it holds app.py, "
                         "otherwise the current directory)")
    args = ap.parse_args()
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    repo = os.path.abspath(args.repo or (here if os.path.exists(os.path.join(here, "app.py")) else os.getcwd()))
    if not os.path.exists(os.path.join(repo, "app.py")):
        sys.exit(f"{repo} is not a checkout of the monitor (no app.py)")
    out_dir = os.path.abspath(os.path.expanduser(args.out))
    if out_dir == repo or out_dir.startswith(repo + os.sep):
        sys.exit("--out must be outside the checkout, which deploy.sh owns")

    load_settings(repo)
    conn = connect()
    try:
        db = read_database(conn)
    finally:
        conn.close()

    today = datetime.date.today().isoformat()
    commit = git(repo, "rev-parse", "--short", "HEAD").strip() or "unknown"
    tables = db["tables"]

    refs, functions, routes, in_code = analyse_code(repo, tables)
    endpoints = endpoints_by_table(functions, routes)
    families = family_of_nightly(repo)

    history, expected = defaultdict(list), {}
    base = handwritten_baseline(repo)
    origins = {}
    if base:
        sha, date, sql = base
        for t, cols in parse_creates(sql).items():
            expected[t] = dict(cols)
            origins[t] = baseline_origin(repo, t) or f"{sha} {date}"
    else:
        warn("no hand-written schema.sql in git history: tables older than schema/ have no baseline")
    for path in migrations_in_order(repo):
        name = "schema/" + os.path.basename(path)
        events, changes = parse_migration(open(path, encoding="utf-8").read())
        for t, action, detail in events:
            history[t].append((name, action, detail))
        for t, op, c, typ in changes:
            if op == "create":            # CREATE TABLE IF NOT EXISTS: a no-op on a table that exists
                expected.setdefault(t, typ)
                continue
            cols = expected.setdefault(t, {})
            if op == "drop":
                cols.pop(c, None)
            else:
                cols[c] = typ

    # Checks, on stderr
    for t in tables:
        if t not in DESCRIPTIONS:
            warn(f"table {t} has no entry in DESCRIPTIONS")
        elif DESCRIPTIONS[t]["group"] in ("conspicuity", "patterns", "quality") and t not in families:
            warn(f"{t} is described as nightly ({DESCRIPTIONS[t]['group']}) but is not in nightly.FAMILIES")
        elif t in families and DESCRIPTIONS[t]["group"] not in (families[t], "quality"):
            warn(f"{t} is in nightly family {families[t]} but described as {DESCRIPTIONS[t]['group']}")
    for t in DESCRIPTIONS:
        if t not in tables:
            warn(f"DESCRIPTIONS has {t}, which is not in the database")
    core = {t for t in tables if any(program_of(rel) != "one-off tool" for rel, _ in refs.get(t, {}))}
    for t in tables:
        if t not in core:
            warn(f"table {t} is not referenced by app.py, sources.py, nightly.py or recorder.py"
                 + (" (only by one-off tools)" if refs.get(t) else ""))
    for t in sorted(in_code - set(tables)):
        warn(f"the code names table {t} in SQL, and the database has no such table")
    for t in tables:
        if t not in expected:
            warn(f"table {t} is in no migration and not in the hand-written schema.sql")
            continue
        have = {c["name"]: c["type"].lower() for c in db["columns"][t]}
        want = expected[t]
        for c in have.keys() - want.keys():
            warn(f"drift: {t}.{c} ({have[c]}) is in the database and in no migration")
        for c in want.keys() - have.keys():
            warn(f"drift: {t}.{c} is in the migrations and not in the database")
        for c in have.keys() & want.keys():
            if have[c] != want[c]:
                warn(f"drift: {t}.{c} is {have[c]} in the database, {want[c]} in the migrations")

    ctx = {"refs": refs, "endpoints": endpoints, "families": families, "history": history,
           "baseline": base, "origins": origins}
    sql = render_schema_sql(db, today, commit)
    md = render_schema_md(db, ctx, today, commit)
    # The files carry DDL and metadata only; refuse to write if a secret slipped in.
    secret = os.getenv("DB_PASSWORD")
    for name, text in (("schema.sql", sql), ("SCHEMA.md", md)):
        if (secret and secret in text) or re.search(r"IDENTIFIED BY|PASSWORD\s*'|^\s*INSERT\s", text, re.I | re.M):
            sys.exit(f"{name} would contain a credential or data; nothing written")
    os.makedirs(out_dir, exist_ok=True)
    for name, text in (("schema.sql", sql), ("SCHEMA.md", md)):
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as f:
            f.write(text)
    groups = defaultdict(int)
    for t in tables:
        groups[DESCRIPTIONS.get(t, {}).get("group", "undescribed")] += 1
    print(f"{len(tables)} tables (" + ", ".join(f"{k} {v}" for k, v in groups.items()) + f"), "
          f"{len(warnings)} warnings; wrote {out_dir}/schema.sql and SCHEMA.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
